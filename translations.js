// Current language
let currentLanguage = localStorage.getItem('language') || 'en';

// Get translation
function t(key) {
    return translations[currentLanguage][key] || translations['en'][key] || key;
}

// Change language
function changeLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    applyLanguage();
}

// Apply language to page
function applyLanguage() {
    const html = document.documentElement;
    const body = document.body;

    if (currentLanguage === 'ar') {
        html.setAttribute('lang', 'ar');
        html.setAttribute('dir', 'rtl');
        body.style.direction = 'rtl';
        body.style.textAlign = 'right';
        document.documentElement.style.direction = 'rtl';
    } else {
        html.setAttribute('lang', 'en');
        html.setAttribute('dir', 'ltr');
        body.style.direction = 'ltr';
        body.style.textAlign = 'left';
        document.documentElement.style.direction = 'ltr';
    }

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const attr = element.getAttribute('data-i18n-attr');
        const value = t(key);

        if (attr) {
            element.setAttribute(attr, value);
        } else {
            // Use innerHTML if VALUE contains HTML tags, otherwise use textContent
            if (value && value.includes('<')) {
                element.innerHTML = value;
            } else {
                element.textContent = value;
            }
        }
    });

    // Update language toggle button
    updateLanguageToggle();
}

// Update language toggle button
function updateLanguageToggle() {
    const langBtn = document.getElementById('language-toggle');
    if (langBtn) {
        langBtn.textContent = currentLanguage === 'en' ? 'ar' : 'en';
        langBtn.setAttribute('data-lang', currentLanguage === 'en' ? 'ar' : 'en');
    }

    // Update mobile language toggle
    const mobileLangToggle = document.getElementById('language-mobile-toggle');
    if (mobileLangToggle) {
        mobileLangToggle.textContent = currentLanguage === 'en' ? 'ar' : 'en';
    }
}

// Initialize on page load
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyLanguage);
} else {
    applyLanguage();
}
